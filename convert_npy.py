#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Data format conversion module

Convert EC forecast CSV and observation CSV files into numpy array format
(.npy) for subsequent model training.

Founded in 2023-07-17
Modified in 2026-09-17
@author: yinlb
"""

import os
import pathlib
import sys
import typing

import arrow
import numpy as np
import pandas as pd

from src import utils

# EC element list (30 in total), consistent with extract_ec.py
# Surface elements: 2T, MSL, 2D, 10U, 10V
# Level elements (1000/950/925/900/850 hPa): T, GH, R, U, V
ELEMENTS = (
    # Surface elements
    '2T', 'MSL', '2D', '10U', '10V',
    # 1000 hPa
    'T_1000', 'GH_1000', 'R_1000', 'U_1000', 'V_1000',
    # 950 hPa
    'T_950', 'GH_950', 'R_950', 'U_950', 'V_950',
    # 925 hPa
    'T_925', 'GH_925', 'R_925', 'U_925', 'V_925',
    # 900 hPa
    'T_900', 'GH_900', 'R_900', 'U_900', 'V_900',
    # 850 hPa
    'T_850', 'GH_850', 'R_850', 'U_850', 'V_850'
)

# Required observation columns (8 wind elements). Column names are kept in
# Chinese because they must match the external observation CSV files.
OBS_COLUMNS = [
    '区站号',
    '2分钟平均风向(角度)',
    '2分钟平均风速',
    '10分钟平均风向(角度)',
    '10分钟平均风速',
    '小时内最大风速的风向',
    '最大风速',
    '极大风速的风向(角度)',
    '极大风速',
]

# ==================== Parameters ====================
# Number of hourly lead times per sample.
N_LEAD_HOURS = 85
# NWP forecast lead time step in hours (3-hourly within N_LEAD_HOURS).
NWP_LEAD_STEP = 3
# ====================================================

# Number of observation data columns (OBS_COLUMNS includes the station ID).
N_OBS_ELEMENTS = len(OBS_COLUMNS) - 1


def main(
    nwp_csv_path: str,
    obs_csv_path: str,
    output_path: str,
    station_info_path: str,
    year: int,
) -> None:
    """
    Convert CSV data into npy format.

    Read EC forecast data and observation data, convert them into numpy
    arrays and save them for model training.

    Args:
        nwp_csv_path: Directory of EC forecast CSV files (generated by
            extract_ec.py).
        obs_csv_path: Directory of national station observation CSV files.
        output_path: Output directory for npy files.
        station_info_path: Station information CSV file path.
        year: Year to process (2017-2022).


    Raises:
        FileNotFoundError: If the station information file does not exist.
    """
    # ---- 1. Initialization: read station info and pre-allocate arrays ----
    station_df = pd.read_csv(
        station_info_path,
        encoding='gb2312',
        low_memory=False,
    )
    station_ids = station_df.loc[:, '台站号'].to_list()
    station_ids.sort()
    station_count = len(station_ids)

    time_begin = arrow.get(str(year))
    time_end = time_begin.shift(years=1)
    # One sample every 12 hours (EC forecast initial times).
    sample_count = round(
        (time_end - time_begin).total_seconds() / 3600 / 12
    )
    # NWP: Numerical Weather Prediction
    nwp_data = np.zeros(
        (sample_count, N_LEAD_HOURS, station_count, len(ELEMENTS)),
        dtype=np.float32,
    ) + np.nan
    # OBS: Observation
    obs_data = np.zeros(
        (sample_count, N_LEAD_HOURS, station_count, N_OBS_ELEMENTS),
        dtype=np.float32,
    ) + np.nan
    print(f'Processing year {year}, sample_count = {sample_count}')

    nwp_dir = pathlib.Path(nwp_csv_path)
    obs_dir = pathlib.Path(obs_csv_path)
    output_dir = pathlib.Path(output_path)
    os.makedirs(output_dir, exist_ok=True)

    # ---- 2. Process EC forecast data (read CSV and save as npy) ----
    for sample_idx in range(sample_count):
        forecast_ref_time = time_begin.shift(hours=12 * sample_idx)
        for lead_time in range(0, N_LEAD_HOURS, NWP_LEAD_STEP):
            filename = '{:s}.{:03d}.csv'.format(
                forecast_ref_time.format('YYYYMMDDHH'), lead_time
            )
            year_str = forecast_ref_time.format('YYYY')
            file_path = nwp_dir / year_str / filename
            if file_path.exists():
                df = pd.read_csv(file_path, low_memory=False)
                df.sort_values(by=['id'], inplace=True)
                df.reset_index(drop=True, inplace=True)
                for elem_idx, element in enumerate(ELEMENTS):
                    nwp_data[sample_idx, lead_time, :, elem_idx] = df.loc[
                        :, element
                    ]
    np.save(file=output_dir / 'nwp{:d}.npy'.format(year), arr=nwp_data)

    # ---- 3. Process observation data (read CSV and save as npy) ----
    for sample_idx in range(sample_count):
        for lead_time in range(N_LEAD_HOURS):
            valid_time = time_begin.shift(hours=12 * sample_idx + lead_time)
            filename = valid_time.format('YYYYMMDDHH') + '.csv'
            file_path = obs_dir / valid_time.format('YYYY') / filename
            if file_path.exists():
                df = pd.read_csv(file_path, low_memory=False)
                df = df.loc[:, OBS_COLUMNS]
                df.sort_values(by=['区站号'], inplace=True)
                df.reset_index(drop=True, inplace=True)
                for obs_var_idx in range(N_OBS_ELEMENTS):
                    if len(df) == station_count:
                        obs_data[sample_idx, lead_time, :, obs_var_idx] = (
                            df.iloc[:, obs_var_idx + 1]
                        )
                    else:
                        for row_idx in range(len(df)):
                            sta_id = df.iloc[row_idx, 0]
                            if sta_id in station_ids:
                                station_idx = station_ids.index(sta_id)
                                obs_data[
                                    sample_idx, lead_time, station_idx,
                                    obs_var_idx
                                ] = df.iloc[row_idx, obs_var_idx + 1]
    np.save(file=output_dir / 'ob{:d}.npy'.format(year), arr=obs_data)


if __name__ == '__main__':
    print('Program convert_npy.py started')
    total_start = arrow.now()

    if len(sys.argv) == 1:
        cfg = utils.load_config()
        paths = cfg['paths']
        years: typing.List[int] = cfg['constants']['years']
        for year in years:
            main(
                nwp_csv_path=paths['ec_station'],
                obs_csv_path=paths['station_obs'],
                output_path=paths['wind_data'],
                station_info_path=paths['station_csv'],
                year=year,
            )
    elif len(sys.argv) == 6:
        main(
            nwp_csv_path=sys.argv[1],
            obs_csv_path=sys.argv[2],
            output_path=sys.argv[3],
            station_info_path=sys.argv[4],
            year=int(sys.argv[5]),
        )

    total_elapsed = (arrow.now() - total_start).total_seconds()
    print(
        'Program convert_npy.py finished, total time '
        f'{utils.format_time(total_elapsed)}'
    )
